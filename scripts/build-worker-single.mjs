#!/usr/bin/env node
// The Worker as ONE file, for the copy-and-paste path in the Cloudflare editor.
// cf-worker/worker.js imports ./fints-banks.js, ./wallets.js and ./push.js; the
// dashboard's "Edit code" takes a single file, so pasting worker.js alone gives
// a Worker that cannot start. This bundles the four files into
// cf-worker/worker.single.js (readable, not minified). The Deploy button and
// `wrangler deploy` keep using worker.js.
//
// Run: npm run build:worker   (test/worker-single.test.js fails when the
// committed file is out of date)
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SINGLE_FILE = join(root, 'cf-worker', 'worker.single.js');

const BANNER = [
  '// MAERMIN Worker - single file for the Cloudflare editor ("Edit code" -> paste -> Deploy).',
  '// GENERATED by `npm run build:worker` from cf-worker/worker.js and the files it imports.',
  '// Do not edit by hand; change cf-worker/*.js and rebuild.'
].join('\n');

export async function bundleWorker() {
  const result = await build({
    entryPoints: [join(root, 'cf-worker', 'worker.js')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    minify: false,
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: BANNER },
    write: false,
    logLevel: 'silent'
  });
  // esbuild writes the platform's line endings nowhere; keep LF so the
  // committed file compares equal on every OS.
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleWorker();
  await writeFile(SINGLE_FILE, text);
  console.log(`[build:worker] cf-worker/worker.single.js  ${(text.length / 1024).toFixed(0)} KB`);
}
