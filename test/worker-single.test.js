// The copy-and-paste Worker (cf-worker/worker.single.js). worker.js imports
// ./fints-banks.js, ./wallets.js and ./push.js, so pasted alone into the
// Cloudflare editor it cannot start; the setup wizard, API Settings and the
// docs hand out the one-file build instead. This keeps that file current and
// equivalent to worker.js, and checks that the copy button never hands out a
// multi-file source.
// Run: node test/worker-single.test.js
'use strict';
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

let passed = 0, failed = 0;
function ok(name, cond, detail) {
  if (cond) { passed++; console.log('  ✓ ' + name); }
  else { failed++; console.error('  ✗ ' + name + (detail ? '  — ' + detail : '')); }
}

(async function run() {
const root = path.join(__dirname, '..');
const lf = (s) => s.replace(/\r\n/g, '\n');
const O = require('../onboarding.js');
const multi = readFileSync(path.join(root, 'cf-worker/worker.js'), 'utf8');
const single = lf(readFileSync(path.join(root, 'cf-worker/worker.single.js'), 'utf8'));

console.log('single-file Worker:');
const { bundleWorker } = await import(pathToFileURL(path.join(root, 'scripts/build-worker-single.mjs')).href);
const fresh = await bundleWorker();
ok('cf-worker/worker.single.js is up to date (run npm run build:worker)', fresh === single,
  'committed ' + single.length + ' chars, fresh build ' + fresh.length);
ok('worker.js itself imports sibling files (why the one-file build exists)', /from '\.\/push\.js'/.test(multi) && !O.isSingleFile(multi));
ok('the one-file build imports nothing', O.isSingleFile(single) && !/^\s*import\s/m.test(single));
ok('it says it is generated', /^\/\/ MAERMIN Worker - single file/.test(single) && /GENERATED by `npm run build:worker`/.test(single));

const W = await import('../cf-worker/worker.js');
const S = await import('../cf-worker/worker.single.js');
ok('same exports as worker.js', Object.keys(S).sort().join() === Object.keys(W).sort().join(), Object.keys(S).sort().join());
ok('same WORKER_VERSION', S.WORKER_VERSION === W.WORKER_VERSION && S.WORKER_VERSION === O.EXPECTED_WORKER_VERSION, S.WORKER_VERSION);
ok('fetch, scheduled (push cron) and the SyncRoom Durable Object are there',
  typeof S.default.fetch === 'function' && typeof S.default.scheduled === 'function' && typeof S.SyncRoom === 'function');

const realFetch = globalThis.fetch;
globalThis.fetch = async () => { throw new Error('no upstream expected'); };
try {
  const req = () => new Request('https://w.example.dev/?action=version', { headers: { Origin: 'http://localhost:8080' } });
  const a = await (await W.default.fetch(req(), {}, {})).json();
  const b = await (await S.default.fetch(req(), {}, {})).json();
  ok('?action=version answers the same', JSON.stringify(a) === JSON.stringify(b), JSON.stringify(b).slice(0, 120));
} finally { globalThis.fetch = realFetch; }

console.log('copy button source:');
const res = (status, body) => Promise.resolve({ ok: status === 200, status, text: () => Promise.resolve(body) });
ok('the wizard fetches the one-file build', O.WORKER_FILE === 'cf-worker/worker.single.js' && /\/cf-worker\/worker\.single\.js$/.test(O.GITHUB_WORKER_URL));
let asked = [];
const got = await O.fetchWorkerSource({ fetch: (p) => { asked.push(p); return res(200, single); } });
ok('default path is the one-file build', asked[0] === 'cf-worker/worker.single.js' && got === single, asked.join());
let rejected = false;
await O.fetchWorkerSource({ paths: ['a', 'b'], fetch: () => res(200, multi) }).catch(() => { rejected = true; });
ok('a multi-file source is never handed out (falls back to GitHub)', rejected);
const second = await O.fetchWorkerSource({ paths: ['a', 'b'], fetch: (p) => res(200, p === 'a' ? multi : single) });
ok('skips a multi-file answer and takes the next path', second === single);

console.log('build and docs:');
const buildSrc = readFileSync(path.join(root, 'build.mjs'), 'utf8');
ok('build.mjs ships the file in dist/cf-worker/', /cf-worker', 'worker\.single\.js'/.test(buildSrc));
const readme = readFileSync(path.join(root, 'README.md'), 'utf8');
const workerDoc = readFileSync(path.join(root, 'docs/WORKER.md'), 'utf8');
ok('README: by-hand path pastes worker.single.js', /paste \[`cf-worker\/worker\.single\.js`\]/.test(readme) && !/paste \[`cf-worker\/worker\.js`\]/.test(readme));
ok('README: update path pastes worker.single.js', /paste the new `cf-worker\/worker\.single\.js`/.test(readme) && !/paste the new `cf-worker\/worker\.js`/.test(readme));
ok('docs/WORKER.md: by-hand path pastes worker.single.js', /paste `cf-worker\/worker\.single\.js`/.test(workerDoc) && !/paste `cf-worker\/worker\.js`/.test(workerDoc));
const renderer = readFileSync(path.join(root, 'renderer.js'), 'utf8');
ok('API Settings update steps name worker.single.js', /'cf-worker\/worker\.single\.js'\)/.test(renderer) && !/'cf-worker\/worker\.js'\)/.test(renderer));

console.log('\n  ' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
})();
